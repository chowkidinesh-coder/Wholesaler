// t('key', { name: 'x' }) – falls back to English, then to the key itself
function t(key, vars) {
  let s = (I18N[currentLang] && I18N[currentLang][key]);
  if (s === undefined) s = I18N.en[key];
  if (s === undefined) s = key;
  return vars ? s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? vars[k] : m)) : s;
}
